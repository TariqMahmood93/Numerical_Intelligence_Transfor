#!/usr/bin/env python3
"""Export experiment results as LaTeX macros for the discussion paper.

    python src/export_latex.py                     # reads ./results, ./data -> writes paper/numbers.tex
    python src/export_latex.py --root RUN_DIR --out paper/numbers.tex

The paper reads every number through \\res{config}{metric}, \\respm{config}{metric} and \\teach{key}.
Undefined values print as a red [TBD], so the paper compiles before and after the HPC run.
Values are copied from results/metrics.json (mean over seeds, std when >1 seed); nothing is rounded
other than to 3 decimals for display.
"""
from __future__ import annotations

import argparse
import json
import os

import numpy as np
import pandas as pd


def flatten(d, prefix=""):
    out = {}
    for k, v in d.items():
        key = f"{prefix}{k}"
        if isinstance(v, dict):
            if k == "per_dimension":
                continue
            out.update(flatten(v, key + "."))
        elif isinstance(v, (int, float)) and not isinstance(v, bool) and v is not None:
            out[key] = float(v)
    return out


def tex_escape(s: str) -> str:
    for a, b in (("\\", r"\textbackslash{}"), ("_", r"\_"), ("%", r"\%"), ("&", r"\&"), ("#", r"\#"), ("$", r"\$")):
        s = s.replace(a, b)
    return s


def fmt(x, nd=3):
    if x is None or not np.isfinite(x):
        return None
    if float(x).is_integer() and abs(x) >= 10:
        return f"{int(x):,}".replace(",", "{,}")
    return f"{x:.{nd}f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    root = a.root
    out = a.out or os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "paper", "numbers.tex")
    lines = ["% Auto-generated by src/export_latex.py -- do not edit by hand."]

    def define(prefix, name, value):
        if value is not None:
            lines.append(rf"\expandafter\def\csname {prefix}@{name}\endcsname{{{value}}}")

    mpath = os.path.join(root, "results", "metrics.json")
    metrics = json.load(open(mpath)) if os.path.exists(mpath) else {}
    if metrics:
        lines.append(r"\def\ResultsAvailable{}")
    for cfg, by_seed in metrics.items():
        flat = pd.DataFrame([flatten(v) for v in by_seed.values()])
        mean, std = flat.mean(), (flat.std(ddof=1) if len(flat) > 1 else None)
        for m, v in mean.items():
            define("res", f"{cfg}@{m}", fmt(v))
            if std is not None and np.isfinite(std[m]) and std[m] > 0:
                define("resstd", f"{cfg}@{m}", fmt(std[m]))
        define("res", f"{cfg}@n_seeds", str(len(flat)))
        prof = next(iter(by_seed.values())).get("cosine_profile", {})
        for ptype, val in prof.items():
            define("res", f"{cfg}@cos.{ptype}", fmt(val["mean"]))
            define("res", f"{cfg}@cosn.{ptype}", str(val["n"]))

    tpath = os.path.join(root, "results", "tables", "teacher_accuracy.json")
    if os.path.exists(tpath):
        t = json.load(open(tpath))
        for k, v in t.items():
            if isinstance(v, bool):
                continue
            if isinstance(v, (int, float)):
                define("teach", k, str(int(v)) if k.startswith("n_") else fmt(float(v)))
            elif isinstance(v, str):
                define("teach", k, tex_escape(v))
        if t.get("is_mock"):
            lines.append(r"\def\ResultsAreMock{}")

    epath = os.path.join(root, "results", "environment.json")
    if os.path.exists(epath):
        env = json.load(open(epath))
        define("env", "hardware", tex_escape(str(env.get("hardware_summary"))))
        define("env", "torch", tex_escape(str(env.get("torch"))))
        define("env", "python", tex_escape(str(env.get("python"))))
        define("env", "minutes", fmt(env.get("total_seconds", float("nan")) / 60, 1))
        if env.get("smoke"):
            lines.append(r"\def\ResultsAreMock{}")

    dpath = os.path.join(root, "data", "numerical_intelligence_dataset.csv")
    if os.path.exists(dpath):
        df = pd.read_csv(dpath)
        define("data", "n", fmt(len(df)) if len(df) >= 10 else str(len(df)))
        for s, n in df.split.value_counts().items():
            define("data", f"split.{s}", fmt(n) if n >= 10 else str(n))
        sw = os.path.join(root, "data", "stress_words_test.csv")
        if os.path.exists(sw):
            define("data", "stress", str(len(pd.read_csv(sw))))
        define("data", "groups_crossing", str(int((df.groupby("equivalence_group").split.nunique() > 1).sum())))

    os.makedirs(os.path.dirname(out), exist_ok=True)
    fig_src = os.path.join(root, "results", "figures")
    if os.path.isdir(fig_src):  # copy figures next to the paper so \includegraphics finds them
        import shutil
        fig_dst = os.path.join(os.path.dirname(out), "figures")
        os.makedirs(fig_dst, exist_ok=True)
        for f in os.listdir(fig_src):
            if f.endswith(".png"):
                shutil.copy2(os.path.join(fig_src, f), os.path.join(fig_dst, f))
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {len(lines)} lines to {out}")


if __name__ == "__main__":
    main()
